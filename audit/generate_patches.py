"""Generate edge patches using Gemini Flash.

Usage:
    python -m audit.generate_patches descriptions   # Fill empty descriptions
    python -m audit.generate_patches orphans         # Generate edges for orphan nodes
    python -m audit.generate_patches all             # Both
    python -m audit.generate_patches descriptions --dry-run  # Preview without API calls
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
from pathlib import Path
from typing import Any

import yaml

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parent.parent
GRAPH_FILE = PROJECT_ROOT / "taxonomy" / "local_governance_graph.yaml"
OUTPUT_FILE = PROJECT_ROOT / "taxonomy" / "edge_patches_generated.yaml"

DESCRIPTION_BATCH_SIZE = 20
ORPHAN_BATCH_SIZE = 10
RATE_LIMIT_SLEEP = 1.0  # seconds between API calls

MODEL_NAME = "gemini-2.0-flash"

# ---------------------------------------------------------------------------
# Gemini client
# ---------------------------------------------------------------------------


def _get_model():
    """Initialize and return the Gemini generative model."""
    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not api_key:
        print("ERROR: Set GEMINI_API_KEY or GOOGLE_API_KEY environment variable.", file=sys.stderr)
        sys.exit(1)

    import google.generativeai as genai

    genai.configure(api_key=api_key)
    return genai.GenerativeModel(MODEL_NAME)


def _call_gemini(model, prompt: str) -> str:
    """Send a prompt to Gemini and return the text response."""
    response = model.generate_content(prompt)
    return response.text


# ---------------------------------------------------------------------------
# Robust JSON parsing
# ---------------------------------------------------------------------------


def _parse_json_response(text: str) -> Any:
    """Parse JSON from an LLM response, handling markdown fences and quirks."""
    # Strip markdown code fences
    cleaned = re.sub(r"^```(?:json)?\s*\n?", "", text.strip(), flags=re.MULTILINE)
    cleaned = re.sub(r"\n?```\s*$", "", cleaned.strip(), flags=re.MULTILINE)
    cleaned = cleaned.strip()

    # Try direct parse first
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # Remove trailing commas before ] or }
    cleaned = re.sub(r",\s*([}\]])", r"\1", cleaned)
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # Try to extract the first JSON array or object
    for pattern in [r"\[[\s\S]*\]", r"\{[\s\S]*\}"]:
        match = re.search(pattern, cleaned)
        if match:
            candidate = match.group(0)
            candidate = re.sub(r",\s*([}\]])", r"\1", candidate)
            try:
                return json.loads(candidate)
            except json.JSONDecodeError:
                continue

    print(f"WARNING: Could not parse JSON from response:\n{text[:500]}", file=sys.stderr)
    return None


# ---------------------------------------------------------------------------
# YAML I/O
# ---------------------------------------------------------------------------


def _load_graph_yaml() -> dict:
    """Load the local governance graph YAML."""
    if not GRAPH_FILE.exists():
        print(f"ERROR: Graph file not found: {GRAPH_FILE}", file=sys.stderr)
        sys.exit(1)
    return yaml.safe_load(GRAPH_FILE.read_text())


def _load_output() -> dict:
    """Load existing output file or return empty structure."""
    if OUTPUT_FILE.exists():
        data = yaml.safe_load(OUTPUT_FILE.read_text())
        if data is not None:
            return data
    return {"edges": [], "description_fills": []}


def _save_output(data: dict) -> None:
    """Write output YAML with a header comment."""
    header = (
        "# Auto-generated by audit/generate_patches.py\n"
        "# Review before merging into production graph\n\n"
    )
    body = yaml.dump(
        data,
        default_flow_style=False,
        sort_keys=False,
        allow_unicode=True,
    )
    OUTPUT_FILE.write_text(header + body)


# ---------------------------------------------------------------------------
# Descriptions mode
# ---------------------------------------------------------------------------


def _find_edges_without_descriptions(graph_data: dict) -> list[dict]:
    """Return edges that have no description key or empty description."""
    edges_missing = []
    for edge in graph_data.get("edges", []) or []:
        desc = edge.get("description")
        if not desc or (isinstance(desc, str) and not desc.strip()):
            edges_missing.append(edge)
    return edges_missing


def _build_node_lookup(graph_data: dict) -> dict[str, dict]:
    """Build a dict of node_id -> {aliases, category}."""
    lookup = {}
    for node in graph_data.get("nodes", []) or []:
        nid = node["id"]
        lookup[nid] = {
            "aliases": node.get("aliases", []),
            "category": node.get("category", ""),
        }
    return lookup


def _description_prompt(batch: list[dict], node_lookup: dict[str, dict]) -> str:
    """Build the prompt for generating edge descriptions."""
    edges_json = []
    for edge in batch:
        src, dst = edge["from"], edge["to"]
        src_info = node_lookup.get(src, {})
        dst_info = node_lookup.get(dst, {})
        edges_json.append({
            "from": src,
            "from_aliases": src_info.get("aliases", []),
            "from_category": src_info.get("category", ""),
            "to": dst,
            "to_aliases": dst_info.get("aliases", []),
            "to_category": dst_info.get("category", ""),
            "type": edge.get("type", ""),
        })

    return f"""You are an expert on Indian governance, infrastructure, and policy systems.

Below are edges from a causal knowledge graph about local governance in India. Each edge connects two concepts with a relationship type (PRODUCES, AFFECTS, REGULATES, DISRUPTS, etc.).

For each edge, write a concise 1-2 sentence description explaining the causal relationship. Be specific to the Indian context where applicable.

Return ONLY a JSON array with objects having these keys:
- "from": the source node ID (unchanged)
- "to": the target node ID (unchanged)
- "description": your 1-2 sentence description

Edges:
{json.dumps(edges_json, indent=2)}

Return valid JSON only. No markdown, no explanation outside the JSON."""


def _already_filled(output_data: dict, src: str, dst: str) -> bool:
    """Check if a description fill already exists in the output."""
    for fill in output_data.get("description_fills", []):
        if fill["from"] == src and fill["to"] == dst:
            return True
    return False


def run_descriptions(dry_run: bool = False) -> None:
    """Generate descriptions for edges missing them."""
    graph_data = _load_graph_yaml()
    node_lookup = _build_node_lookup(graph_data)
    edges_missing = _find_edges_without_descriptions(graph_data)

    if not edges_missing:
        print("No edges missing descriptions.")
        return

    output_data = _load_output()

    # Filter out already-generated descriptions
    remaining = [
        e for e in edges_missing
        if not _already_filled(output_data, e["from"], e["to"])
    ]

    if not remaining:
        print(f"All {len(edges_missing)} descriptions already generated.")
        return

    total = len(remaining)
    batches = [remaining[i:i + DESCRIPTION_BATCH_SIZE] for i in range(0, total, DESCRIPTION_BATCH_SIZE)]
    num_batches = len(batches)
    generated_count = len(edges_missing) - total  # already done

    print(f"Edges missing descriptions: {len(edges_missing)}")
    print(f"Already generated: {generated_count}")
    print(f"Remaining: {total} in {num_batches} batches")

    if dry_run:
        for i, batch in enumerate(batches, 1):
            print(f"\n--- Batch {i}/{num_batches} ({len(batch)} edges) ---")
            prompt = _description_prompt(batch, node_lookup)
            print(f"Prompt length: {len(prompt)} chars")
            print(f"Edges: {', '.join(f'{e['from']}→{e['to']}' for e in batch[:5])}")
            if len(batch) > 5:
                print(f"  ... and {len(batch) - 5} more")
        return

    model = _get_model()

    for i, batch in enumerate(batches, 1):
        generated_count_before = len(output_data.get("description_fills", []))
        print(f"Batch {i}/{num_batches}: {generated_count_before}/{len(edges_missing)} descriptions generated")

        prompt = _description_prompt(batch, node_lookup)

        try:
            response_text = _call_gemini(model, prompt)
            parsed = _parse_json_response(response_text)
        except Exception as e:
            print(f"  ERROR in batch {i}: {e}", file=sys.stderr)
            time.sleep(RATE_LIMIT_SLEEP)
            continue

        if parsed is None:
            print(f"  WARNING: Could not parse response for batch {i}, skipping")
            time.sleep(RATE_LIMIT_SLEEP)
            continue

        if not isinstance(parsed, list):
            parsed = [parsed]

        for item in parsed:
            if not isinstance(item, dict):
                continue
            src = item.get("from", "")
            dst = item.get("to", "")
            desc = item.get("description", "")
            if src and dst and desc:
                if not _already_filled(output_data, src, dst):
                    output_data.setdefault("description_fills", []).append({
                        "from": src,
                        "to": dst,
                        "description": desc,
                    })

        # Save incrementally
        _save_output(output_data)
        time.sleep(RATE_LIMIT_SLEEP)

    final_count = len(output_data.get("description_fills", []))
    print(f"\nDone. {final_count} total description fills saved to {OUTPUT_FILE}")


# ---------------------------------------------------------------------------
# Orphans mode
# ---------------------------------------------------------------------------


def _find_orphan_nodes() -> tuple[list[dict], Any]:
    """Find orphan nodes (degree 0) using TaxonomyMerger.

    Returns (orphan_info_list, merged_graph).
    """
    from graph.merge import TaxonomyMerger

    merger = TaxonomyMerger(root=PROJECT_ROOT)
    G = merger.merge()

    orphans = []
    for nid in G.nodes():
        if G.degree(nid) == 0:
            attrs = G.nodes[nid]
            orphans.append({
                "id": nid,
                "aliases": attrs.get("aliases", []),
                "category": attrs.get("category", ""),
            })

    return orphans, G


def _get_nearby_nodes(G, orphan_category: str, exclude_id: str, limit: int = 10) -> list[dict]:
    """Get up to `limit` nodes in the same category as context."""
    candidates = []
    for nid, attrs in G.nodes(data=True):
        if nid == exclude_id:
            continue
        if attrs.get("category", "") == orphan_category and G.degree(nid) > 0:
            candidates.append({
                "id": nid,
                "aliases": attrs.get("aliases", []),
                "degree": G.degree(nid),
            })

    # Sort by degree descending so we pick well-connected nodes
    candidates.sort(key=lambda x: x["degree"], reverse=True)
    return candidates[:limit]


def _orphan_prompt(orphan_batch: list[dict], nearby_map: dict[str, list[dict]]) -> str:
    """Build prompt for generating edges for orphan nodes."""
    context = []
    for orphan in orphan_batch:
        oid = orphan["id"]
        nearby = nearby_map.get(oid, [])
        context.append({
            "orphan_id": oid,
            "orphan_aliases": orphan["aliases"],
            "orphan_category": orphan["category"],
            "nearby_connected_nodes": [
                {"id": n["id"], "aliases": n["aliases"]}
                for n in nearby
            ],
        })

    return f"""You are an expert on Indian governance, infrastructure, and policy systems.

Below are "orphan" nodes from a causal knowledge graph — they exist but have NO edges connecting them to other nodes. For each orphan, I've also listed nearby well-connected nodes in the same category.

For each orphan, suggest 2-3 edges that would meaningfully connect it to existing nodes. Use these edge types: PRODUCES, CONSUMES, AFFECTS, REGULATES, DISRUPTS, SUPPLIES, DEPENDS_ON, LOCATED_IN, MANAGES, FUNDS, CONNECTS.

Return ONLY a JSON array of edge objects with these keys:
- "from": source node ID
- "to": target node ID
- "type": one of the edge types above
- "description": 1-2 sentence description of the causal relationship

The "from" or "to" should be the orphan node; the other end should be an existing node (from the nearby list or any well-known node in the graph).

Orphans and their context:
{json.dumps(context, indent=2)}

Return valid JSON only. No markdown, no explanation outside the JSON."""


def _edge_already_exists(output_data: dict, src: str, dst: str) -> bool:
    """Check if an edge already exists in the generated output."""
    for edge in output_data.get("edges", []):
        if edge["from"] == src and edge["to"] == dst:
            return True
    return False


def run_orphans(dry_run: bool = False) -> None:
    """Generate connecting edges for orphan nodes."""
    print("Building merged graph...")
    orphans, G = _find_orphan_nodes()

    if not orphans:
        print("No orphan nodes found.")
        return

    output_data = _load_output()

    # Filter out orphans that already have generated edges
    existing_orphan_ids = set()
    for edge in output_data.get("edges", []):
        existing_orphan_ids.add(edge["from"])
        existing_orphan_ids.add(edge["to"])

    remaining = [o for o in orphans if o["id"] not in existing_orphan_ids]

    if not remaining:
        print(f"All {len(orphans)} orphans already have generated edges.")
        return

    total = len(remaining)
    batches = [remaining[i:i + ORPHAN_BATCH_SIZE] for i in range(0, total, ORPHAN_BATCH_SIZE)]
    num_batches = len(batches)

    print(f"Orphan nodes: {len(orphans)}")
    print(f"Already addressed: {len(orphans) - total}")
    print(f"Remaining: {total} in {num_batches} batches")

    if dry_run:
        for i, batch in enumerate(batches, 1):
            nearby_map = {}
            for orphan in batch:
                nearby_map[orphan["id"]] = _get_nearby_nodes(G, orphan["category"], orphan["id"])
            prompt = _orphan_prompt(batch, nearby_map)
            print(f"\n--- Batch {i}/{num_batches} ({len(batch)} orphans) ---")
            print(f"Prompt length: {len(prompt)} chars")
            print(f"Orphans: {', '.join(o['id'] for o in batch)}")
        return

    model = _get_model()

    for i, batch in enumerate(batches, 1):
        edges_before = len(output_data.get("edges", []))
        print(f"Batch {i}/{num_batches}: {edges_before} orphan edges generated so far")

        nearby_map = {}
        for orphan in batch:
            nearby_map[orphan["id"]] = _get_nearby_nodes(G, orphan["category"], orphan["id"])

        prompt = _orphan_prompt(batch, nearby_map)

        try:
            response_text = _call_gemini(model, prompt)
            parsed = _parse_json_response(response_text)
        except Exception as e:
            print(f"  ERROR in batch {i}: {e}", file=sys.stderr)
            time.sleep(RATE_LIMIT_SLEEP)
            continue

        if parsed is None:
            print(f"  WARNING: Could not parse response for batch {i}, skipping")
            time.sleep(RATE_LIMIT_SLEEP)
            continue

        if not isinstance(parsed, list):
            parsed = [parsed]

        for item in parsed:
            if not isinstance(item, dict):
                continue
            src = item.get("from", "")
            dst = item.get("to", "")
            etype = item.get("type", "AFFECTS")
            desc = item.get("description", "")
            if src and dst and desc:
                if not _edge_already_exists(output_data, src, dst):
                    output_data.setdefault("edges", []).append({
                        "from": src,
                        "to": dst,
                        "type": etype,
                        "description": desc,
                    })

        # Save incrementally
        _save_output(output_data)
        time.sleep(RATE_LIMIT_SLEEP)

    final_count = len(output_data.get("edges", []))
    print(f"\nDone. {final_count} total orphan edges saved to {OUTPUT_FILE}")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate edge patches using Gemini Flash.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "mode",
        choices=["descriptions", "orphans", "all"],
        help="Which patches to generate",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview batches and prompts without making API calls",
    )
    args = parser.parse_args()

    if args.mode in ("descriptions", "all"):
        print("=" * 60)
        print("MODE: descriptions")
        print("=" * 60)
        run_descriptions(dry_run=args.dry_run)

    if args.mode in ("orphans", "all"):
        if args.mode == "all":
            print()
        print("=" * 60)
        print("MODE: orphans")
        print("=" * 60)
        run_orphans(dry_run=args.dry_run)


if __name__ == "__main__":
    main()
